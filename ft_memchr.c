#include "libft.h"

void	*ft_memchr(const void *s, int c, size_t n)
{
	unsigned char	tmp;
	unsigned char	*cs;

	tmp = (unsigned char)c;
	cs = (unsigned char *)s;
	while (n--)
	{
		if (*cs == tmp)
			return ((void *)cs);
		cs++;
	}
	return (NULL);
}
