#include "libft.h"

char	*ft_strdup(const char *s)
{
	char	*re;

	re = malloc(ft_strlen(s) + 1);
	if (!re)
		return (NULL);
	ft_memcpy(re, s, ft_strlen(s) + 1);
	return (re);
}
