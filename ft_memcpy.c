#include "libft.h"

void	*ft_memcpy(void *dst, const void *src, size_t n)
{
	unsigned char	*dst_tmp;
	unsigned char	*src_tmp;

	dst_tmp = (unsigned char *)dst;
	src_tmp = (unsigned char *)src;
	while (n--)
	{
		*(dst_tmp) = *(src_tmp);
		dst_tmp++;
		src_tmp++;
	}
	return (dst);
}
